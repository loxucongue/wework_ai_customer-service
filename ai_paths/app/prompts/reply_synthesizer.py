def build_parallel_reply_messages(user_payload: dict[str, Any], *, json_dumps) -> list[dict[str, str]]:
    return [
        {"role": "system", "content": PARALLEL_REPLY_SYSTEM_PROMPT},
        {"role": "user", "content": json_dumps(user_payload)},
    ]
